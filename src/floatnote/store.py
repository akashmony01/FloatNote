"""SQLite storage for bug (session) notes, idea notes and projects.

Session notes = kind 'bug' that are not archived yet, per project. "Copy all"
archives them under one batch_id, so `undo` can bring the last batch back.
Ideas are one shared list (project_id is NULL).
"""

import sqlite3
import threading
import uuid
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path

SCHEMA_VERSION = 2
GENERAL_ID = 1  # the default project; can be renamed, never deleted

_SCHEMA = """
CREATE TABLE IF NOT EXISTS notes (
  id          INTEGER PRIMARY KEY,
  kind        TEXT NOT NULL CHECK (kind IN ('bug','idea')),
  text        TEXT NOT NULL,
  created_at  TEXT NOT NULL,
  updated_at  TEXT,
  done        INTEGER NOT NULL DEFAULT 0,
  archived_at TEXT,
  batch_id    TEXT,
  duration_s  REAL
);
CREATE INDEX IF NOT EXISTS notes_session ON notes (kind, archived_at);
"""

_SCHEMA_V2 = """
CREATE TABLE IF NOT EXISTS projects (
  id          INTEGER PRIMARY KEY,
  name        TEXT NOT NULL UNIQUE COLLATE NOCASE,
  folder      TEXT,
  created_at  TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS settings (
  key   TEXT PRIMARY KEY,
  value TEXT
);
"""


@dataclass
class Note:
    id: int
    kind: str
    text: str
    created_at: str
    updated_at: str | None
    done: bool
    archived_at: str | None
    batch_id: str | None
    duration_s: float | None
    project_id: int | None = None

    def to_dict(self) -> dict:
        return dict(self.__dict__)


@dataclass
class Project:
    id: int
    name: str
    folder: str | None
    created_at: str

    def to_dict(self) -> dict:
        return dict(self.__dict__)


def _now() -> str:
    return datetime.now().isoformat(timespec="seconds")


def format_paste(intro: str, notes: list[Note]) -> str:
    """The text "paste all" puts on the clipboard."""
    lines = [f"{i}. {n.text}" for i, n in enumerate(notes, 1)]
    body = "\n".join(lines)
    return f"{intro}\n\n{body}\n" if intro else body + "\n"


def format_ideas_markdown(ideas: list[Note]) -> str:
    open_ = [n for n in ideas if not n.done]
    done = [n for n in ideas if n.done]
    out = ["# FloatNote ideas", "", "_Generated by FloatNote. Edits here are overwritten; edit ideas in the app._", ""]
    for title, items, box in (("Open", open_, " "), ("Done", done, "x")):
        out.append(f"## {title} ({len(items)})")
        out.append("")
        out += [f"- [{box}] {n.text} _({n.created_at[:10]})_" for n in items] or ["_None._"]
        out.append("")
    return "\n".join(out)


class Store:
    def __init__(self, path: Path, readonly: bool = False, export_path: Path | None = None):
        self.path = path
        self.export_path = export_path
        if readonly:
            self._db = sqlite3.connect(f"file:{path}?mode=ro", uri=True, check_same_thread=False)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            self._db = sqlite3.connect(path, check_same_thread=False)
            self._migrate()
        self._db.row_factory = sqlite3.Row
        self._lock = threading.Lock()
        self.export_ideas()

    def _migrate(self) -> None:
        self._db.execute("PRAGMA journal_mode=WAL")
        version = self._db.execute("PRAGMA user_version").fetchone()[0]
        if version < 1:
            self._db.executescript(_SCHEMA)
        if version < 2:
            # Projects: existing bugs move into "General". Safe to re-run if an
            # earlier attempt was interrupted.
            self._db.executescript(_SCHEMA_V2)
            columns = [r[1] for r in self._db.execute("PRAGMA table_info(notes)")]
            if "project_id" not in columns:
                self._db.execute("ALTER TABLE notes ADD COLUMN project_id INTEGER REFERENCES projects(id)")
            self._db.execute("INSERT OR IGNORE INTO projects (id, name, created_at) VALUES (?,?,?)",
                             (GENERAL_ID, "General", _now()))
            self._db.execute("UPDATE notes SET project_id=? WHERE kind='bug'", (GENERAL_ID,))
        if version < SCHEMA_VERSION:
            self._db.execute(f"PRAGMA user_version={SCHEMA_VERSION}")
            self._db.commit()

    def close(self) -> None:
        self._db.close()

    def _query(self, sql: str, args=()) -> list[Note]:
        with self._lock:
            rows = self._db.execute(sql, args).fetchall()
        return [Note(**{**dict(r), "done": bool(r["done"])}) for r in rows]

    def _write(self, sql: str, args=()) -> int:
        with self._lock, self._db:
            count = self._db.execute(sql, args).rowcount
        self.export_ideas()
        return count

    def export_ideas(self) -> None:
        """Rewrite the readable ideas.md next to the database (if configured)."""
        if self.export_path is None:
            return
        import os
        import tempfile

        text = format_ideas_markdown(self.ideas(include_done=True))
        # A unique temp file, so two writers (app + CLI) never trip over each other.
        fd, tmp = tempfile.mkstemp(dir=self.export_path.parent, prefix=".ideas-", suffix=".tmp")
        with os.fdopen(fd, "w") as f:
            f.write(text)
        os.replace(tmp, self.export_path)

    # ---- reading ---------------------------------------------------------

    def get(self, note_id: int) -> Note | None:
        rows = self._query("SELECT * FROM notes WHERE id=?", (note_id,))
        return rows[0] if rows else None

    def session_notes(self, project_id: int | None = None) -> list[Note]:
        """Bugs waiting to be copied; for one project, or all projects if None."""
        if project_id is None:
            return self._query(
                "SELECT * FROM notes WHERE kind='bug' AND archived_at IS NULL ORDER BY id")
        return self._query(
            "SELECT * FROM notes WHERE kind='bug' AND archived_at IS NULL AND project_id=? ORDER BY id",
            (project_id,))

    def ideas(self, include_done: bool = False) -> list[Note]:
        where = "" if include_done else "AND done=0"
        return self._query(f"SELECT * FROM notes WHERE kind='idea' {where} ORDER BY id DESC")

    # ---- writing ---------------------------------------------------------

    def add(self, kind: str, text: str, duration_s: float | None = None,
            project_id: int | None = None) -> int:
        """Add a note. Bugs belong to a project (default: General); ideas never do."""
        if kind == "bug" and project_id is None:
            project_id = GENERAL_ID
        if kind == "idea":
            project_id = None
        with self._lock, self._db:
            cur = self._db.execute(
                "INSERT INTO notes (kind, text, created_at, duration_s, project_id) VALUES (?,?,?,?,?)",
                (kind, text, _now(), duration_s, project_id))
        if kind == "idea":
            self.export_ideas()
        return cur.lastrowid

    def update_text(self, note_id: int, text: str) -> bool:
        return self._write("UPDATE notes SET text=?, updated_at=? WHERE id=?",
                           (text, _now(), note_id)) == 1

    def set_kind(self, note_id: int, kind: str, project_id: int | None = None) -> bool:
        if kind == "idea":
            project_id = None
        elif project_id is None:
            project_id = GENERAL_ID
        return self._write("UPDATE notes SET kind=?, project_id=?, updated_at=? WHERE id=?",
                           (kind, project_id, _now(), note_id)) == 1

    def set_done(self, note_id: int, done: bool) -> bool:
        return self._write("UPDATE notes SET done=?, updated_at=? WHERE id=?",
                           (int(done), _now(), note_id)) == 1

    def delete(self, note_id: int) -> bool:
        return self._write("DELETE FROM notes WHERE id=?", (note_id,)) == 1

    def archive_session(self, note_ids: list[int]) -> str:
        """Archive the given session notes as one batch. Returns the batch id."""
        batch = uuid.uuid4().hex[:12]
        marks = ",".join("?" * len(note_ids))
        self._write(
            f"UPDATE notes SET archived_at=?, batch_id=? "
            f"WHERE id IN ({marks}) AND kind='bug' AND archived_at IS NULL",
            (_now(), batch, *note_ids))
        return batch

    def undo_last_batch(self, project_id: int | None = None) -> int:
        """Bring the most recently archived batch back (of one project, if given).
        Returns how many notes."""
        where = "batch_id IS NOT NULL AND archived_at IS NOT NULL"
        args: tuple = ()
        if project_id is not None:
            where += " AND project_id=?"
            args = (project_id,)
        with self._lock, self._db:
            row = self._db.execute(
                f"SELECT batch_id FROM notes WHERE {where} ORDER BY archived_at DESC, id DESC LIMIT 1",
                args).fetchone()
            if row is None:
                return 0
            return self._db.execute(
                "UPDATE notes SET archived_at=NULL, batch_id=NULL WHERE batch_id=?",
                (row[0],)).rowcount

    # ---- projects --------------------------------------------------------

    def projects(self) -> list[Project]:
        with self._lock:
            rows = self._db.execute("SELECT * FROM projects ORDER BY id").fetchall()
        return [Project(**dict(r)) for r in rows]

    def project(self, project_id: int) -> Project | None:
        return next((p for p in self.projects() if p.id == project_id), None)

    def project_by_name(self, name: str) -> Project | None:
        return next((p for p in self.projects() if p.name.lower() == name.strip().lower()), None)

    def project_for_folder(self, path: str) -> Project | None:
        """The project linked to `path` or a folder above it (closest one wins)."""
        here = Path(path).expanduser().resolve()
        best, best_len = None, -1
        for p in self.projects():
            if not p.folder:
                continue
            folder = Path(p.folder).expanduser().resolve()
            if (here == folder or folder in here.parents) and len(folder.parts) > best_len:
                best, best_len = p, len(folder.parts)
        return best

    def add_project(self, name: str, folder: str | None = None) -> int:
        name = name.strip()
        if not name:
            raise ValueError("Project name can't be empty.")
        if self.project_by_name(name):
            raise ValueError(f'There is already a project called "{name}".')
        with self._lock, self._db:
            cur = self._db.execute("INSERT INTO projects (name, folder, created_at) VALUES (?,?,?)",
                                   (name, folder, _now()))
        return cur.lastrowid

    def rename_project(self, project_id: int, name: str) -> None:
        name = name.strip()
        if not name:
            raise ValueError("Project name can't be empty.")
        other = self.project_by_name(name)
        if other and other.id != project_id:
            raise ValueError(f'There is already a project called "{name}".')
        self._write("UPDATE projects SET name=? WHERE id=?", (name, project_id))

    def set_project_folder(self, project_id: int, folder: str | None) -> None:
        self._write("UPDATE projects SET folder=? WHERE id=?", (folder or None, project_id))

    def delete_project(self, project_id: int, move_bugs_to: int | None = GENERAL_ID) -> None:
        """Delete a project. Its bugs move to another project, or are deleted if None."""
        if project_id == GENERAL_ID:
            raise ValueError("The General project can't be deleted.")
        with self._lock, self._db:
            if move_bugs_to is None:
                self._db.execute("DELETE FROM notes WHERE project_id=?", (project_id,))
            else:
                self._db.execute("UPDATE notes SET project_id=? WHERE project_id=?", (move_bugs_to, project_id))
            self._db.execute("DELETE FROM projects WHERE id=?", (project_id,))
        if self.active_project_id() == project_id:
            self.set_active_project(GENERAL_ID)

    def active_project_id(self) -> int:
        with self._lock:
            row = self._db.execute("SELECT value FROM settings WHERE key='active_project'").fetchone()
        pid = int(row[0]) if row and row[0] else GENERAL_ID
        return pid if self.project(pid) else GENERAL_ID

    def set_active_project(self, project_id: int) -> None:
        with self._lock, self._db:
            self._db.execute("INSERT OR REPLACE INTO settings (key, value) VALUES ('active_project', ?)",
                             (str(project_id),))

    def bug_counts(self) -> dict[int, int]:
        """Waiting bugs per project id."""
        with self._lock:
            rows = self._db.execute("SELECT project_id, COUNT(*) FROM notes WHERE kind='bug' "
                                    "AND archived_at IS NULL GROUP BY project_id").fetchall()
        return {r[0]: r[1] for r in rows}
